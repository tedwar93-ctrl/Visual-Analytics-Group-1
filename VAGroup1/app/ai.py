# 5. TARGET EXPORTED FUNCTION
# ==============================================================================

def generate_insight_narrative(metrics_dict: dict) -> str:
    """
    Main entry point for AI Insight Narrator.
    Signature: generate_insight_narrative(metrics_dict: dict) -> str

    Translates pre-computed promotional and repurchase metrics into an executive-level
    Markdown summary (2 to 3 concise bullet points).

    Execution Workflow:
    1. Low-confidence check: if insufficient_data is True or sample_size_n < 30, returns
       the exact safety statement immediately.
    2. LLM Invocation: attempts generation via authenticated LLM (Gemini or OpenAI).
    3. Post-Processing Audit: audits candidate output for banned terms, causal claims,
       and numerical validity against input metrics.
    4. Deterministic Fallback: if LLM is unavailable, unauthenticated, or fails audit,
       generates the narrative directly via the deterministic template.
    """
    # 1. Automated Low-Confidence Handling
    if is_low_confidence(metrics_dict):
        return INSUFFICIENT_DATA_MESSAGE

    # 2. Check for LLM credentials
    provider, api_key = _get_api_credentials()
    candidate_narrative: Optional[str] = None

    if provider and api_key:
        prompt = _construct_user_prompt(metrics_dict)
        if provider == "gemini":
            candidate_narrative = _call_gemini_api(api_key, prompt)
        elif provider == "openai":
            candidate_narrative = _call_openai_api(api_key, prompt)

        if candidate_narrative:
            candidate_narrative = _strip_markdown_fences(candidate_narrative)
            # 3. Post-Processing Numerical Audit & Guardrail Verification
            if verify_narrative(candidate_narrative, metrics_dict):
                return candidate_narrative

    # 4. Deterministic Template Fallback
    return generate_template_narrative(metrics_dict)

