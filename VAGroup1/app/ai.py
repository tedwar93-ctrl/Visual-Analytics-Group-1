# 2. DETERMINISTIC TEMPLATE FALLBACK
# ==============================================================================

def generate_template_narrative(metrics_dict: Dict[str, Any]) -> str:
    """
    Deterministic template fallback when LLM is unavailable or candidate output
    fails verification audits.

    Surfaces both standard and non-obvious derived metrics:
    Standard:
      - unit_lift_pct, sales_lift_pct, post_vs_pre_unit_pct, post_vs_during_dip_pct
      - avg_days_to_first_post_purchase, post_repurchase_rate_pct, trial_retention_rate_pct,
        interpurchase_day_change
    Non-obvious (surfaced in bullet 3):
      BDA context: household_penetration_lift_pct, spend_per_buyer_change_pct,
                   units_per_buyer_change_pct, revenue_recovery_rate_pct
      Repurchase context: new_buyer_pct, non_returning_buyer_pct, existing_loyal_buyer_pct,
                          avg_pre_interpurchase_days, avg_post_interpurchase_days

    Strictly satisfies all negative constraints: zero banned terms, zero causal claims,
    and 100% grounded in input metrics.
    """
    def _safe(key: str) -> Optional[float]:
        """Return float value if present and not NaN, else None."""
        v = metrics_dict.get(key)
        if v is None:
            return None
        try:
            fv = float(v)
            return None if np.isnan(fv) else fv
        except (ValueError, TypeError):
            return None

    # 1. Identify product
    commodity = metrics_dict.get("commodity_desc")
    product_id = metrics_dict.get("product_id")
    if commodity and product_id:
        product_str = f"{str(commodity).strip()} (Product ID {product_id})"
    elif commodity:
        product_str = str(commodity).strip()
    elif product_id:
        product_str = f"Product ID {product_id}"
    else:
        product_str = "the selected category"

    # Sample size
    sample_size = metrics_dict.get("sample_size_n") or metrics_dict.get("promo_buyers_count")
    sample_str = (
        f"{int(sample_size):,}"
        if isinstance(sample_size, (int, float)) and not np.isnan(float(sample_size))
        else str(sample_size)
    )

    # ── BULLET 1: Promotional Performance (standard + household penetration lift) ──
    unit_lift = _safe("unit_lift_pct")
    sales_lift = _safe("sales_lift_pct")
    hh_pen_lift = _safe("household_penetration_lift_pct")

    lift_clauses: List[str] = []
    if unit_lift is not None:
        lift_clauses.append(f"an observed unit lift of {unit_lift:+.1f}%")
    if sales_lift is not None:
        lift_clauses.append(f"a dollar sales volume lift of {sales_lift:+.1f}%")
    if hh_pen_lift is not None:
        lift_clauses.append(
            f"a household penetration increase of {hh_pen_lift:+.1f}% "
            f"({int(round(abs(hh_pen_lift)))}% {'more' if hh_pen_lift >= 0 else 'fewer'} unique shoppers versus baseline)"
        )

    lift_desc = " along with ".join(lift_clauses) if lift_clauses else "promotional purchasing activity"
    bullet_1 = (
        f"- **Promotional Performance:** During promotional weeks, {product_str} exhibited "
        f"{lift_desc} compared to the pre-promotion baseline across {sample_str} active households."
    )

    # ── BULLET 2: Repurchase Timing & Shopper Cadence ──
    avg_days = _safe("avg_days_to_first_post_purchase")
    repurchase_rate = _safe("post_repurchase_rate_pct")
    cycle_shift = _safe("interpurchase_day_change")
    non_returning = _safe("non_returning_buyer_pct")
    new_buyer = _safe("new_buyer_pct")

    timing_clauses: List[str] = []
    if avg_days is not None:
        timing_clauses.append(
            f"waited an average of {avg_days:.1f} calendar days before making their first return purchase"
        )
    if repurchase_rate is not None:
        timing_clauses.append(
            f"exhibited an observed regular-price repurchase rate of {repurchase_rate:.1f}%"
        )
    if non_returning is not None:
        timing_clauses.append(
            f"with {non_returning:.1f}% of promotional buyers recording no subsequent observed purchases"
        )
    if cycle_shift is not None:
        direction = "elongated" if cycle_shift > 0 else "compressed"
        timing_clauses.append(
            f"showed a shopping cycle that {direction} by {abs(cycle_shift):.1f} days "
            f"(post-promo vs. pre-promo interpurchase interval)"
        )
    if new_buyer is not None:
        timing_clauses.append(
            f"{new_buyer:.1f}% of promotional buyers were first-time purchasers with no prior baseline activity"
        )

    if timing_clauses:
        bullet_2 = (
            "- **Repurchase Timing & Shopper Cadence:** Following promotional events, buyers "
            + ", and ".join(timing_clauses) + "."
        )
    else:
        bullet_2 = (
            "- **Repurchase Timing & Shopper Cadence:** "
            "Subsequent purchasing trends reflect baseline shopping cycle intervals."
        )

    # ── BULLET 3: Non-Obvious Hidden Signals ──
    # BDA signals
    spend_change = _safe("spend_per_buyer_change_pct")
    units_per_buyer_change = _safe("units_per_buyer_change_pct")
    revenue_recovery = _safe("revenue_recovery_rate_pct")
    post_pre_pct = _safe("post_vs_pre_unit_pct")
    post_during_dip = _safe("post_vs_during_dip_pct")
    trial_retention = _safe("trial_retention_rate_pct")
    # Repurchase signals
    loyal_pct = _safe("existing_loyal_buyer_pct")
    pre_cycle = _safe("avg_pre_interpurchase_days")
    post_cycle = _safe("avg_post_interpurchase_days")

    hidden_clauses: List[str] = []

    if spend_change is not None:
        direction = "higher" if spend_change >= 0 else "lower"
        hidden_clauses.append(
            f"per-buyer spending was {abs(spend_change):.1f}% {direction} per trip during the promotion "
            f"compared to baseline — a signal of {'increased basket size' if spend_change >= 0 else 'discount depth reducing per-trip revenue'}"
        )
    if units_per_buyer_change is not None:
        direction = "more" if units_per_buyer_change >= 0 else "fewer"
        hidden_clauses.append(
            f"each active household purchased {abs(units_per_buyer_change):.1f}% {direction} units per trip "
            f"during the promotion versus baseline (per-buyer loading rate)"
        )
    if revenue_recovery is not None:
        hidden_clauses.append(
            f"post-promotion dollar sales volume recovered to {revenue_recovery:.1f}% of the pre-promotion baseline "
            f"({'above' if revenue_recovery >= 100 else 'below'} full recovery)"
        )
    if loyal_pct is not None:
        hidden_clauses.append(
            f"{loyal_pct:.1f}% of promotional buyers were pre-existing baseline purchasers "
            f"(the remaining buyers represent new-to-product trial shoppers)"
        )
    if pre_cycle is not None and post_cycle is not None:
        hidden_clauses.append(
            f"average inter-purchase intervals shifted from {pre_cycle:.1f} days (pre-promo) "
            f"to {post_cycle:.1f} days (post-promo) among repeat buyers"
        )
    if post_during_dip is not None:
        hidden_clauses.append(
            f"a volume dip of {post_during_dip:.1f}% relative to peak promotional volume"
        )
    if post_pre_pct is not None:
        hidden_clauses.append(
            f"weekly unit volume difference of {post_pre_pct:+.1f}% versus the pre-promotion baseline"
        )
    if trial_retention is not None:
        hidden_clauses.append(
            f"a trial buyer retention rate of {trial_retention:.1f}% at regular price"
        )

    if hidden_clauses:
        bullet_3 = (
            "- **Hidden Shopper Signals:** Deeper analysis of the same episode reveals: "
            + "; ".join(hidden_clauses[:3]) + "."  # cap at 3 to keep bullet readable
        )
        bullets = [bullet_1, bullet_2, bullet_3]
    else:
        bullets = [bullet_1, bullet_2]

    return "\n".join(bullets)


