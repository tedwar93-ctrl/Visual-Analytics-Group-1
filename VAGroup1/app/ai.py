def _get_api_credentials() -> Tuple[Optional[str], Optional[str]]:
    """
    Retrieves LLM API credentials from Streamlit runtime secrets or environment variables.
    Returns (provider, api_key) or (None, None).
    """
    # 1. Check Streamlit runtime secrets
    try:
        import streamlit as st
        if hasattr(st, "secrets"):
            for key in ("GEMINI_API_KEY", "GOOGLE_API_KEY"):
                if key in st.secrets and st.secrets[key]:
                    return "gemini", str(st.secrets[key]).strip()
            for key in ("OPENAI_API_KEY",):
                if key in st.secrets and st.secrets[key]:
                    return "openai", str(st.secrets[key]).strip()
    except Exception:
        pass

    # 2. Check environment variables
    for key in ("GEMINI_API_KEY", "GOOGLE_API_KEY"):
        val = os.environ.get(key)
        if val and val.strip():
            return "gemini", val.strip()

    for key in ("OPENAI_API_KEY",):
        val = os.environ.get(key)
        if val and val.strip():
            return "openai", val.strip()

    return None, None


def _construct_user_prompt(metrics_dict: Dict[str, Any]) -> str:
    """Formats the metrics into an explicit prompt for the LLM."""
    lines = [
        "Please generate a 2 to 3 bullet point executive summary using ONLY the following verified metrics:",
    ]
    for k, v in sorted(metrics_dict.items()):
        if v is not None and not (isinstance(v, float) and np.isnan(v)):
            lines.append(f"- {k}: {v}")
    lines.append(
        "\nRemember: Use '-' bullet points. Do not invent any numbers. Do not use banned financial words (profit, margin, cost, COGS, ROI). Describe trends neutrally without causal claims."
    )
    return "\n".join(lines)


def _call_gemini_api(api_key: str, prompt: str) -> Optional[str]:
    """Calls Google Gemini REST API using requests."""
    try:
        import requests
        url = f"https://generativelanguage.googleapis.com/v1beta/models/gemini-1.5-flash:generateContent?key={api_key}"
        headers = {"Content-Type": "application/json"}
        payload = {
            "contents": [
                {
                    "parts": [
                        {"text": f"{SYSTEM_PROMPT}\n\n{prompt}"}
                    ]
                }
            ],
            "generationConfig": {
                "temperature": 0.2,
                "maxOutputTokens": 300,
            },
        }
        resp = requests.post(url, headers=headers, json=payload, timeout=8)
        if resp.status_code == 200:
            data = resp.json()
            candidates = data.get("candidates", [])
            if candidates:
                parts = candidates[0].get("content", {}).get("parts", [])
                if parts:
                    return parts[0].get("text", "").strip()
    except Exception:
        pass
    return None


def _call_openai_api(api_key: str, prompt: str) -> Optional[str]:
    """Calls OpenAI REST API using requests."""
    try:
        import requests
        url = "https://api.openai.com/v1/chat/completions"
        headers = {
            "Authorization": f"Bearer {api_key}",
            "Content-Type": "application/json",
        }
        payload = {
            "model": "gpt-4o-mini",
            "messages": [
                {"role": "system", "content": SYSTEM_PROMPT},
                {"role": "user", "content": prompt},
            ],
            "temperature": 0.2,
            "max_tokens": 300,
        }
        resp = requests.post(url, headers=headers, json=payload, timeout=8)
        if resp.status_code == 200:
            data = resp.json()
            choices = data.get("choices", [])
            if choices:
                return choices[0].get("message", {}).get("content", "").strip()
    except Exception:
        pass
    return None


def _strip_markdown_fences(text: str) -> str:
    """Removes enclosing markdown code fences if present."""
    text = text.strip()
    if text.startswith("```markdown"):
        text = text[len("```markdown"):].strip()
    elif text.startswith("```"):
        text = text[3:].strip()
    if text.endswith("```"):
        text = text[:-3].strip()
    return text


