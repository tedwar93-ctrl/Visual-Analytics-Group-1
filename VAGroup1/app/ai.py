# 3. POST-PROCESSING NUMERICAL AUDIT & GUARDRAIL VERIFICATION
# ==============================================================================

def extract_numbers_from_text(text: str) -> List[float]:
    """
    Parses candidate text and extracts all numerical values.
    Supports integers, decimals, comma-separated thousands, and signed numbers.
    Ignores markdown list bullets (e.g. '-' followed by a space).
    """
    # Regex matches numbers with optional sign and comma thousands separators
    # Ensures preceding char is not an alphanumeric or slash, and succeeding char is not an alphanumeric
    pattern = r"(?<![a-zA-Z0-9_/])[-+−]?\d{1,3}(?:,\d{3})*(?:\.\d+)?(?![a-zA-Z0-9_])|(?<![a-zA-Z0-9_/])[-+−]?\d+(?:\.\d+)?(?![a-zA-Z0-9_])"
    raw_matches = re.findall(pattern, text)
    numbers: List[float] = []

    for match in raw_matches:
        cleaned = match.replace(",", "").replace("−", "-").strip()
        if cleaned in ("-", "+", ""):
            continue
        try:
            val = float(cleaned)
            numbers.append(val)
        except ValueError:
            continue

    return numbers


def extract_allowed_numbers_from_dict(metrics_dict: Dict[str, Any]) -> List[float]:
    """
    Collects all legitimate numerical figures from the input dictionary,
    including exact values, absolute values, and common roundings.
    """
    allowed: List[float] = []
    for k, v in metrics_dict.items():
        if v is None:
            continue
        if isinstance(v, (int, float)):
            try:
                fv = float(v)
                if not np.isnan(fv):
                    allowed.append(fv)
                    allowed.append(abs(fv))
                    allowed.append(round(fv, 1))
                    allowed.append(round(fv, 2))
                    allowed.append(float(int(round(fv))))
            except (ValueError, OverflowError):
                pass
        elif isinstance(v, str):
            # Extract numbers from string values (e.g. product IDs or codes)
            str_nums = re.findall(r"\b\d+(?:\.\d+)?\b", v)
            for sn in str_nums:
                try:
                    fv = float(sn)
                    allowed.append(fv)
                except ValueError:
                    pass
    return allowed


def is_number_allowed(num: float, allowed_numbers: List[float]) -> bool:
    """
    Checks if an extracted number matches any allowed number from the input dataset.
    Permits slight formatting differences (e.g. 1 decimal rounding, sign differences).
    """
    for allowed in allowed_numbers:
        # Exact or close floating point match
        if math.isclose(num, allowed, rel_tol=1e-3, abs_tol=0.06):
            return True
        if math.isclose(abs(num), abs(allowed), rel_tol=1e-3, abs_tol=0.06):
            return True
        # Integer equality
        if int(round(abs(num))) == int(round(abs(allowed))) and abs(num - allowed) < 1.0:
            return True
    return False


def verify_narrative(candidate_text: str, metrics_dict: Dict[str, Any]) -> bool:
    """
    Two-tier verification of candidate generated text:
    1. Negative Constraint Check: Banned financial terms (profit, margin, COGS, cost, ROI).
    2. Behavioral Constraint Check: Causal claims or physical pantry storage claims.
    3. Numerical Audit: Every extracted number must be accounted for in the input metrics.
    
    Returns True if narrative passes all checks, False otherwise.
    """
    if not candidate_text or not isinstance(candidate_text, str):
        return False

    # 1. Banned financial terms check
    if BANNED_FINANCIAL_PATTERN.search(candidate_text):
        return False

    # 2. Causal / physical claims check
    for pattern in BANNED_CAUSAL_PATTERNS:
        if pattern.search(candidate_text):
            return False

    # 3. Post-Processing Numerical Audit
    extracted_nums = extract_numbers_from_text(candidate_text)
    if not extracted_nums:
        # A narrative without any data figures fails fact-bound grounding
        return False

    allowed_nums = extract_allowed_numbers_from_dict(metrics_dict)
    for num in extracted_nums:
        if not is_number_allowed(num, allowed_nums):
            # Unverified or invented figure found
            return False

    return True


