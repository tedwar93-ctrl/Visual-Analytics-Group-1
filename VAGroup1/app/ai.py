"""
app/ai.py
---------
ITCS 5122 - Grocery Promotion & Stockpiling Explorer
AI Insight Narrator Module

Core Business Function:
Acts as an evidence-based narrative generator for a Regional Grocery Category Manager.
Receives pre-computed promotional and repurchase metrics generated by the analytics
pipeline (analytics.py and data_preparation.py) and translates them into clear,
executive-level Markdown summaries.

Enforces:
1. Strict fact-bound grounding (no invented, estimated, or unverified numbers).
2. Prohibited financial terminology (strictly banned: profit, margin, COGS, cost, ROI).
3. Neutral behavioral descriptions (no causal claims or assertions of physical pantry storage).
4. Automated low-confidence handling (returns exact safety statement if insufficient_data is True
   or sample_size_n < 30).
5. Post-processing numerical audit and deterministic template fallback.
"""

from __future__ import annotations

import math
import os
import re
from typing import Any, Dict, List, Optional, Tuple

import numpy as np


# ==============================================================================
# CONSTANTS & GUARDRAIL DEFINITIONS
# ==============================================================================

INSUFFICIENT_DATA_MESSAGE: str = (
    "Data history is insufficient to draw reliable post-promotional purchasing patterns for this selection."
)

# Strictly banned financial terms (case-insensitive words/stems)
BANNED_FINANCIAL_WORDS: Tuple[str, ...] = (
    "profit",
    "profits",
    "profitable",
    "profitability",
    "margin",
    "margins",
    "cogs",
    "cost",
    "costs",
    "costing",
    "roi",
)

BANNED_FINANCIAL_PATTERN = re.compile(
    r"\b(" + "|".join(BANNED_FINANCIAL_WORDS) + r")\b",
    re.IGNORECASE,
)

# Banned causal and physical storage assertions
BANNED_CAUSAL_PATTERNS = [
    re.compile(r"\b(cause|causes|caused|causing|causation)\b", re.IGNORECASE),
    re.compile(r"\bpantry\s+(?:storage|stockpil\w+)\b", re.IGNORECASE),
    re.compile(r"\b(?:stored|stockpiled)\s+in\s+(?:their|the)\s+pantr\w+\b", re.IGNORECASE),
    re.compile(r"\bphysically\s+(?:stored|stockpiled)\b", re.IGNORECASE),
]

# System prompt for LLM generation
SYSTEM_PROMPT = """You are an AI Insight Narrator for a Regional Grocery Category Manager.
Translate pre-computed promotional and repurchase metrics into clear, executive-level Markdown summaries.

CRITICAL MANDATORY GUARDRAILS:
1. STRICT FACT-BOUND GROUNDING:
- State ONLY figures explicitly provided in the input metrics.
- You are strictly prohibited from inventing, estimating, projecting, or rounding numbers not found directly in the input dataset.
- Do NOT use numbered lists (like 1., 2., 3.) because extra numbers will fail verification. Use hyphens (-) for bullet points.
- Provide exactly 3 bullet points.

2. PROHIBITED FINANCIAL TERMINOLOGY:
- STRICTLY BANNED WORDS: "profit", "margin", "COGS", "cost", and "ROI".
- Wholesale cost data is unavailable. Describe financial activity strictly using terms like "sales volume", "unit lift", "realized price", or "revenue patterns".

3. NEUTRAL BEHAVIORAL DESCRIPTIONS:
- Describe patterns neutrally as "observed associations", "purchasing trends", or "shopper response patterns".
- NEVER claim that promotions caused customer behavior or state as fact that households physically stored or stockpiled inventory in their pantries.

4. BULLET STRUCTURE GUIDANCE:
- Bullet 1: Summarize the core promotional performance (unit lift, sales volume lift, household penetration).
- Bullet 2: Cover repurchase timing and shopper cadence (days to return, repurchase rate, cycle shift, new vs. loyal buyer split).
- Bullet 3 (REQUIRED): Surface the most interesting NON-OBVIOUS hidden signal from the metrics —
  something a manager would not see by just reading the page. Good candidates include:
  per-buyer spend change, units-per-buyer loading rate, revenue recovery rate vs. baseline,
  the share of promo buyers who were brand-new trial shoppers, the share who never returned,
  or the direction and magnitude of shopping cycle elongation. Pick the single most striking one.
"""


# ==============================================================================
# 1. LOW-CONFIDENCE & DATA QUALITY CHECKS
# ==============================================================================

def is_low_confidence(metrics_dict: Optional[Dict[str, Any]]) -> bool:
    """
    Evaluates whether the input metrics fail minimum safety thresholds:
    - metrics_dict is None, empty, or not a dict
    - insufficient_data is True
    - sample_size_n (or promo_buyers_count) is None or < 30
    """
    if not metrics_dict or not isinstance(metrics_dict, dict):
        return True

    if bool(metrics_dict.get("insufficient_data", False)):
        return True

    sample_size = metrics_dict.get("sample_size_n")
    if sample_size is None:
        sample_size = metrics_dict.get("promo_buyers_count")

    if sample_size is None:
        return True

    try:
        val = float(sample_size)
        if np.isnan(val) or val < 30:
            return True
    except (ValueError, TypeError):
        return True

    return False


